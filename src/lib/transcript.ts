export interface TranscriptSegment {
  text: string;
  /** Start time in seconds. */
  offset: number;
  /** Duration in seconds. */
  duration: number;
}

export interface CaptionTrack {
  languageCode: string;
  name: string;
  autoGenerated: boolean;
}

export interface TranscriptResult {
  segments: TranscriptSegment[];
  language: string;
  autoGenerated: boolean;
  /** Set when YouTube machine-translated the captions into the requested language. */
  translatedFrom?: string;
  availableLanguages: CaptionTrack[];
  title?: string;
  channel?: string;
  /** Set when the requested translation was refused and the original language came back instead. */
  translationUnavailable?: string;
  /** Which route produced the transcript, for diagnostics. */
  source: string;
}

/** Inner-tube client types that still hand out caption tracks without a proof-of-origin token (verified Nov 2026). */
const CAPTION_CLIENTS = ['ANDROID', 'IOS'] as const;

interface RawTrack {
  base_url: string;
  language_code: string;
  vss_id?: string;
  name?: { text?: string; toString?: () => string };
  kind?: string;
  is_translatable?: boolean;
}

interface Track {
  languageCode: string;
  autoGenerated: boolean;
  translatable?: boolean;
  /** Caption track id such as ".en" or "a.en"; selects the track in the transcript panel. */
  vssId?: string;
  baseUrl: string;
  name: string;
}

interface VideoCaptions {
  tracks: Track[];
  title?: string;
  channel?: string;
}

export function cleanTranscriptText(text: string): string {
  return text
    .replace(/\[(music|applause|laughter|silence|inaudible|__)\]/gi, '')
    .replace(/\s+/g, ' ')
    .trim();
}

const ENTITIES: Record<string, string> = { '&amp;': '&', '&lt;': '<', '&gt;': '>', '&quot;': '"', '&#39;': "'", '&apos;': "'", '&nbsp;': ' ' };

export function decodeEntities(text: string): string {
  return text
    .replace(/&(amp|lt|gt|quot|#39|apos|nbsp);/g, (m) => ENTITIES[m] ?? m)
    .replace(/&#(\d+);/g, (_, n) => String.fromCodePoint(Number(n)))
    .replace(/&#x([0-9a-f]+);/gi, (_, n) => String.fromCodePoint(parseInt(n, 16)));
}

function baseLang(code: string): string {
  return code.toLowerCase().split(/[-_]/)[0];
}

/**
 * Pick the best track: the requested language (human captions first), otherwise the
 * language the video is spoken in (the auto-generated track), otherwise English, otherwise
 * anything. When the requested language is missing but YouTube can translate, ask for that.
 */
export function chooseTrack<T extends { languageCode: string; autoGenerated: boolean; translatable?: boolean }>(
  tracks: T[],
  requested?: string,
): { track: T; translateTo?: string } | null {
  if (tracks.length === 0) return null;
  const human = (t: T) => !t.autoGenerated;
  const matches = (lang: string) => (t: T) => t.languageCode.toLowerCase() === lang.toLowerCase() || baseLang(t.languageCode) === baseLang(lang);

  if (requested) {
    const exact = tracks.filter(matches(requested));
    const pick = exact.find(human) ?? exact[0];
    if (pick) return { track: pick };
  }

  const spoken = tracks.find((t) => t.autoGenerated);
  const original = spoken ? (tracks.filter(matches(spoken.languageCode)).find(human) ?? spoken) : undefined;
  const english = tracks.filter(matches('en'));
  const fallback = original ?? english.find(human) ?? english[0] ?? tracks.find(human) ?? tracks[0];

  if (requested && fallback.translatable !== false) return { track: fallback, translateTo: requested };
  return { track: fallback };
}

interface Json3 {
  events?: Array<{ tStartMs?: number; dDurationMs?: number; segs?: Array<{ utf8?: string }> }>;
}

export function parseJson3(body: string): TranscriptSegment[] {
  const data = JSON.parse(body) as Json3;
  const segments: TranscriptSegment[] = [];
  for (const ev of data.events ?? []) {
    if (!ev.segs) continue;
    const text = decodeEntities(ev.segs.map((s) => s.utf8 ?? '').join('')).replace(/\s+/g, ' ').trim();
    if (!text) continue;
    segments.push({ text, offset: (ev.tStartMs ?? 0) / 1000, duration: (ev.dDurationMs ?? 0) / 1000 });
  }
  return segments;
}

/**
 * Whether a player response speaks for the video itself, not just the client that asked. YouTube
 * answers UNPLAYABLE ("not available on this app") when it refuses a client, so only ERROR counts
 * as the video being gone.
 */
function aboutTheVideo(error: unknown): boolean {
  const kind = classify(error);
  if (kind === 'private' || kind === 'age_restricted') return true;
  return kind === 'unavailable' && /^ERROR/.test(error instanceof Error ? error.message : String(error));
}

/** The caption track list, from the first player client that answers. */
async function loadCaptions(videoId: string): Promise<VideoCaptions> {
  const { yt } = await getInstance();
  let lastError: unknown;
  for (const client of CAPTION_CLIENTS) {
    try {
      const info = await yt.getBasicInfo(videoId, { client });
      const status = info.playability_status;
      if (status && status.status !== 'OK') throw new Error(`${status.status}: ${status.reason ?? 'video not playable'}`);
      const raw = (info.captions?.caption_tracks ?? []) as unknown as RawTrack[];
      return {
        tracks: raw.map((t) => ({
          languageCode: t.language_code,
          autoGenerated: t.kind === 'asr',
          translatable: t.is_translatable,
          vssId: t.vss_id,
          baseUrl: t.base_url,
          name: t.name?.text ?? t.name?.toString?.() ?? t.language_code,
        })),
        title: info.basic_info.title,
        channel: info.basic_info.author,
      };
    } catch (error) {
      lastError = error;
      if (aboutTheVideo(error)) throw error;
      debug(`caption list via ${client} failed: ${(error as Error).message}`);
    }
  }
  throw lastError;
}

function available(captions: VideoCaptions | null): CaptionTrack[] {
  return (captions?.tracks ?? []).map((t) => ({ languageCode: t.languageCode, name: t.name, autoGenerated: t.autoGenerated }));
}

/** The caption file itself (timedtext). The only route that can machine-translate. */
async function viaCaptionFile(captions: VideoCaptions, track: Track, translateTo?: string): Promise<TranscriptResult> {
  const url = new URL(track.baseUrl);
  url.searchParams.set('fmt', 'json3');
  if (translateTo) url.searchParams.set('tlang', translateTo);
  return {
    segments: await downloadCaptions(url),
    language: translateTo ?? track.languageCode,
    autoGenerated: track.autoGenerated,
    translatedFrom: translateTo ? track.languageCode : undefined,
    availableLanguages: available(captions),
    title: captions.title,
    channel: captions.channel,
    source: translateTo ? 'caption-file-translated' : 'caption-file',
  };
}

const TRANSCRIPT_PANEL = 'PAmodern_transcript_view';

function varint(n: number): Buffer {
  const out: number[] = [];
  while (n > 0x7f) {
    out.push((n & 0x7f) | 0x80);
    n >>>= 7;
  }
  out.push(n);
  return Buffer.from(out);
}

function protoString(field: number, value: string): Buffer {
  const bytes = Buffer.from(value);
  return Buffer.concat([varint((field << 3) | 2), varint(bytes.length), bytes]);
}

/** Parameters for YouTube's transcript panel: message 149 { 1: video id, 3: 1, 6: caption track id }. */
export function transcriptPanelParams(videoId: string, vssId?: string): string {
  const inner = Buffer.concat([protoString(1, videoId), Buffer.from([0x18, 0x01]), ...(vssId ? [protoString(6, vssId)] : [])]);
  return Buffer.concat([varint((149 << 3) | 2), varint(inner.length), inner]).toString('base64');
}

interface SyncEntry {
  videoTimeMs?: string;
  endTimeMs?: string;
}

/**
 * Read the transcript panel response. Text and whole-second start times come from the panel
 * items; millisecond timings come from the panel's sync data, matched up in order.
 */
export function parseTranscriptPanel(data: unknown): TranscriptSegment[] {
  const items: Array<{ text: string; seconds: number }> = [];
  const sync: SyncEntry[] = [];
  const walk = (node: unknown): void => {
    if (!node || typeof node !== 'object') return;
    if (Array.isArray(node)) {
      node.forEach(walk);
      return;
    }
    const obj = node as Record<string, any>;
    const marker = obj.macroMarkersPanelItemViewModel;
    if (marker) {
      const contents: any[] = marker.item?.timelineItemViewModel?.contentItems ?? [];
      const seg = contents.find((c) => c.transcriptSegmentViewModel)?.transcriptSegmentViewModel;
      if (seg?.simpleText) {
        const start = marker.onTap?.innertubeCommand?.watchEndpoint?.startTimeSeconds;
        items.push({ text: String(seg.simpleText), seconds: typeof start === 'number' ? start : clockToSeconds(seg.timestamp) });
      }
      return;
    }
    const entity = obj.timedMarkersListSyncEntity;
    if (entity) {
      for (const section of entity.timedListData?.sections ?? []) {
        sync.push(...((section.timedSyncDataList ?? []) as SyncEntry[]).filter((e) => e.endTimeMs !== undefined));
      }
      return;
    }
    Object.values(obj).forEach(walk);
  };
  walk(data);

  let cursor = 0;
  const segments = items
    .map((item) => {
      // Sync entries run in segment order; take the next one that starts in the same second.
      let match: SyncEntry | undefined;
      for (let i = cursor; i < sync.length && i < cursor + 3; i++) {
        if (Math.abs(Math.floor(Number(sync[i].videoTimeMs) / 1000) - item.seconds) <= 1) {
          match = sync[i];
          cursor = i + 1;
          break;
        }
      }
      const offset = match ? Number(match.videoTimeMs) / 1000 : item.seconds;
      const duration = match ? Math.max(0, Number(match.endTimeMs) / 1000 - offset) : -1;
      return { text: item.text.replace(/\s+/g, ' ').trim(), offset, duration };
    })
    .filter((s) => s.text);
  segments.forEach((s, i) => {
    if (s.duration < 0) s.duration = i + 1 < segments.length ? Math.max(0, segments[i + 1].offset - s.offset) : 3;
  });
  return segments;
}

function clockToSeconds(clock: unknown): number {
  return String(clock ?? '0')
    .split(':')
    .reduce((total, part) => total * 60 + (Number(part) || 0), 0);
}

/**
 * YouTube's own transcript panel (the "Show transcript" button). A different system from the
 * caption files serves it, so it keeps working while those are rate-limited.
 */
export async function panelSegments(videoId: string, vssId?: string): Promise<TranscriptSegment[]> {
  const { yt } = await getInstance();
  const res = await yt.actions.execute('/get_panel', { panelId: TRANSCRIPT_PANEL, params: transcriptPanelParams(videoId, vssId) });
  const segments = parseTranscriptPanel(res.data);
  if (segments.length === 0) throw new YouTubeToolError('no_captions', `YouTube's transcript panel is empty for ${videoId}.`);
  return segments;
}

const opening = (segments: TranscriptSegment[]) => segments.slice(0, 5).map((s) => s.text).join(' ');

/** Word sets for comparing two transcripts; scripts written without spaces use character pairs. */
function vocabulary(segments: TranscriptSegment[]): Set<string> {
  const text = segments.slice(0, 40).map((s) => s.text).join(' ').toLowerCase();
  const words = new Set<string>();
  for (const [run] of text.matchAll(/\p{L}+/gu)) {
    if (/[\p{Script=Han}\p{Script=Hiragana}\p{Script=Katakana}\p{Script=Thai}]/u.test(run)) {
      for (let i = 0; i < run.length - 1; i++) words.add(run.slice(i, i + 2));
    } else {
      words.add(run);
    }
  }
  return words;
}

/** Shared vocabulary above this means two transcripts are the same language (human vs auto captions of one talk). */
const SAME_LANGUAGE_OVERLAP = 0.25;

export function sameLanguage(a: TranscriptSegment[], b: TranscriptSegment[]): boolean {
  const va = vocabulary(a);
  const vb = vocabulary(b);
  if (!va.size || !vb.size) return false;
  let shared = 0;
  for (const w of va) if (vb.has(w)) shared++;
  return shared / (va.size + vb.size - shared) >= SAME_LANGUAGE_OVERLAP;
}

/**
 * On VPN and cloud IPs YouTube hides the track list, and the panel quietly returns the default
 * track for any caption track the video doesn't have, without saying which language that is.
 * Work out whether the requested language exists, and whether the default already is it.
 */
export async function panelInLanguage(videoId: string, fallback: TranscriptSegment[], requested: string): Promise<{ segments: TranscriptSegment[]; language: string; autoGenerated: boolean }> {
  const unknown = { segments: fallback, language: 'unknown', autoGenerated: false };
  const human = await panelSegments(videoId, `.${requested}`).catch(() => null);
  if (human && opening(human) !== opening(fallback)) return { segments: human, language: requested, autoGenerated: false };
  const auto = await panelSegments(videoId, `a.${requested}`).catch(() => null);
  if (!auto || opening(auto) === opening(fallback)) return unknown;
  // The video has auto captions in the requested language. If the default track reads like them,
  // it is the human track in that language, which beats the auto one.
  if (sameLanguage(auto, fallback)) return { segments: fallback, language: requested, autoGenerated: false };
  return { segments: auto, language: requested, autoGenerated: true };
}

async function viaTranscriptPanel(videoId: string, captions: VideoCaptions | null, track: Track | null, requested?: string): Promise<TranscriptResult> {
  const segments = await panelSegments(videoId, track?.vssId);
  const found = !captions && requested
    ? await panelInLanguage(videoId, segments, requested)
    : { segments, language: track?.languageCode ?? 'unknown', autoGenerated: track?.autoGenerated ?? false };
  return {
    ...found,
    availableLanguages: available(captions),
    title: captions?.title,
    channel: captions?.channel,
    source: 'transcript-panel',
  };
}

async function downloadCaptions(url: URL): Promise<TranscriptSegment[]> {
  const res = await fetch(url, { headers: cookieHeaders() });
  if (res.status === 429) {
    const retryAfter = res.headers.get('retry-after');
    throw new YouTubeToolError('rate_limited', `YouTube returned 429 Too Many Requests for the caption file${retryAfter ? ` (retry after ${retryAfter}s)` : ''}.`);
  }
  if (!res.ok) throw new Error(`Caption download failed with HTTP ${res.status}`);
  const body = await res.text();
  if (!body.trim()) throw new Error('Caption download returned an empty body');
  const segments = parseJson3(body);
  if (segments.length === 0) throw new Error('Caption file had no text');
  return segments;
}

function cookieHeaders(): Record<string, string> {
  const cookie = loadCookies();
  return cookie ? { Cookie: cookie } : {};
}

async function viaTranscriptLibrary(videoId: string, requested: string | undefined): Promise<TranscriptResult> {
  const { listLanguages } = await import('youtube-transcript-plus');
  const headers = cookieHeaders();
  const withCookies = Object.keys(headers).length
    ? {
        videoFetch: ({ url, lang, userAgent }: { url: string; lang?: string; userAgent?: string }) =>
          fetch(url, { headers: { ...headers, ...(lang ? { 'Accept-Language': lang } : {}), ...(userAgent ? { 'User-Agent': userAgent } : {}) } }),
      }
    : {};
  const langs = await listLanguages(videoId, withCookies);
  const tracks = langs.map((l) => ({ ...l, autoGenerated: l.isAutoGenerated }));
  const choice = chooseTrack(tracks, requested);
  if (!choice) throw new YouTubeToolError('no_captions', `Video ${videoId} has no captions.`);
  // This route can't translate, so it returns the best original-language track.
  const segs: LibSegment[] = await fetchTranscript(videoId, { lang: choice.track.languageCode, retries: 1, retryDelay: 1500, ...withCookies });
  return {
    segments: segs.map((s) => ({ text: decodeEntities(s.text).replace(/\s+/g, ' ').trim(), offset: s.offset, duration: s.duration })),
    language: choice.track.languageCode,
    autoGenerated: choice.track.autoGenerated,
    availableLanguages: langs.map((l) => ({ languageCode: l.languageCode, name: l.languageName, autoGenerated: l.isAutoGenerated })),
    source: 'youtube-transcript-plus',
  };
}

/** Last resort: yt-dlp, only when it is already installed (a transcript shouldn't trigger a large download). */
async function viaYtDlp(videoId: string, requested: string | undefined): Promise<TranscriptResult> {
  const ytdlp = await findBinary('yt-dlp', { download: false });
  if (!ytdlp) throw new Error('yt-dlp not installed');
  const dir = mkdtempSync(join(tmpdir(), 'yt-subs-'));
  try {
    const lang = requested ?? 'en';
    const args = ['--skip-download', '--write-subs', '--write-auto-subs', '--sub-format', 'json3', '--sub-langs', `${lang}.*,${lang},en.*,en`, '-o', join(dir, '%(id)s.%(ext)s'), '--no-warnings', '--no-js-runtimes', '--js-runtimes', `node:${process.execPath}`];
    const cookie = loadCookies();
    if (cookie) args.push('--add-header', `Cookie:${cookie}`);
    const proxy = proxyUrl();
    if (proxy) args.push('--proxy', proxy);
    args.push(`https://www.youtube.com/watch?v=${videoId}`);
    await runProcess(ytdlp, args, { timeoutMs: 90_000 });
    const file = readdirSync(dir).find((f) => f.endsWith('.json3'));
    if (!file) throw new YouTubeToolError('no_captions', `yt-dlp found no captions for ${videoId}.`);
    const code = file.split('.').slice(-2, -1)[0] ?? lang;
    return {
      segments: parseJson3(readFileSync(join(dir, file), 'utf8')),
      language: code,
      autoGenerated: false,
      availableLanguages: [],
      source: 'yt-dlp',
    };
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

/**
 * Fetch a transcript through several independent routes, stopping at the first that works.
 * YouTube changes or limits one route at a time, so the chain keeps working when one breaks.
 */
/**
 * Paging through a long transcript calls this once per page, so keep recent results. Identical
 * concurrent requests share one fetch.
 */
const CACHE_TTL_MS = 30 * 60_000;
const CACHE_MAX = 30;
const cache = new Map<string, { at: number; value: Promise<TranscriptResult> }>();

const DAY_MS = 24 * 60 * 60_000;

function diskPath(videoId: string, language?: string): string {
  return join(ensureDataDir('cache'), `transcript-${videoId}-${(language || 'auto').replace(/[^\w-]/g, '')}.json`);
}

function readDisk(videoId: string, language?: string): TranscriptResult | null {
  const days = getConfig().cache.transcriptDays;
  if (!days) return null;
  try {
    const path = diskPath(videoId, language);
    if (!existsSync(path) || Date.now() - statSync(path).mtimeMs > days * DAY_MS) return null;
    return JSON.parse(readFileSync(path, 'utf8')) as TranscriptResult;
  } catch {
    return null;
  }
}

function writeDisk(videoId: string, language: string | undefined, result: TranscriptResult): void {
  if (!getConfig().cache.transcriptDays || result.translationUnavailable) return;
  try { writeFileSync(diskPath(videoId, language), JSON.stringify(result)); } catch { /* cache is best effort */ }
}

/**
 * After YouTube rate-limits the caption server, every further request extends the block. Fail
 * fast for a while instead (cached transcripts keep working).
 */
const COOLDOWN_MS = 2 * 60_000;
/** Which YouTube system a route ends at. A rate limit on one says nothing about the other. */
type Backend = 'panel' | 'caption-file';
const coolingUntil: Record<Backend, number> = { panel: 0, 'caption-file': 0 };
const cooling = (backend: Backend) => Date.now() < coolingUntil[backend];

export function getTranscript(videoId: string, language?: string): Promise<TranscriptResult> {
  const key = `${videoId}|${language ?? ''}`;
  const hit = cache.get(key);
  if (hit && Date.now() - hit.at < CACHE_TTL_MS) return hit.value;
  const stored = readDisk(videoId, language);
  if (stored) return Promise.resolve({ ...stored, source: `${stored.source} (cached)` });
  if (cooling('panel') && cooling('caption-file')) {
    const wait = Math.ceil((Math.min(coolingUntil.panel, coolingUntil['caption-file']) - Date.now()) / 1000);
    return Promise.reject(new YouTubeToolError('rate_limited', `YouTube rate-limited transcript requests from this network a moment ago; pausing for another ${wait}s so the block can clear.`));
  }
  const value = fetchTranscriptChain(videoId, language).then((result) => {
    writeDisk(videoId, language, result);
    return result;
  });
  cache.set(key, { at: Date.now(), value });
  value.catch(() => cache.delete(key));
  while (cache.size > CACHE_MAX) cache.delete(cache.keys().next().value!);
  return value;
}

type Failure = { route: string; kind: FailureKind; message: string };

async function fetchTranscriptChain(videoId: string, language?: string): Promise<TranscriptResult> {
  const requested = language ?? (getConfig().transcript.defaultLanguage || undefined);
  const failures: Failure[] = [];
  const fail = (route: string, error: unknown): FailureKind => {
    const kind = classify(error);
    const message = error instanceof Error ? error.message : String(error);
    debug(`transcript ${videoId} via ${route} failed (${kind}): ${message}`);
    failures.push({ route, kind, message });
    return kind;
  };
  const final = (kind: FailureKind) => kind === 'private' || kind === 'unavailable' || kind === 'age_restricted';

  let captions: VideoCaptions | null = null;
  // When every player client calls the video unavailable, or lists no captions, only the
  // transcript panel is worth asking before giving up: it may still know better.
  let panelOnly = false;
  try {
    captions = await loadCaptions(videoId);
  } catch (error) {
    fail('caption list', error);
    if (aboutTheVideo(error)) giveUp(videoId, failures);
    panelOnly = classify(error) === 'unavailable';
  }
  if (captions && captions.tracks.length === 0) {
    failures.push({ route: 'caption list', kind: 'no_captions', message: 'YouTube lists no caption tracks.' });
    panelOnly = true;
  }
  const choice = captions?.tracks.length ? chooseTrack(captions.tracks, requested) : null;
  const track = choice?.track ?? null;
  const translateTo = choice?.translateTo;

  const routes: Array<[string, Backend, () => Promise<TranscriptResult>]> = [];
  if (captions && track && translateTo) routes.push(['caption file (translated)', 'caption-file', () => viaCaptionFile(captions, track, translateTo)]);
  routes.push(['transcript panel', 'panel', () => viaTranscriptPanel(videoId, captions, track, requested)]);
  if (!panelOnly) {
    if (captions && track) routes.push(['caption file', 'caption-file', () => viaCaptionFile(captions, track)]);
    routes.push(['youtube-transcript-plus', 'caption-file', () => viaTranscriptLibrary(videoId, requested)]);
    routes.push(['yt-dlp', 'caption-file', () => viaYtDlp(videoId, requested)]);
  }

  for (const [route, backend, run] of routes) {
    // Hammering a system that just rate-limited us only extends the block.
    if (cooling(backend)) {
      failures.push({ route, kind: 'rate_limited', message: 'skipped while YouTube cools off from a recent rate limit' });
      continue;
    }
    try {
      const result = await run();
      debug(`transcript ${videoId} via ${route}: ${result.segments.length} segments`);
      const wanted = translateTo ?? (captions ? undefined : requested);
      if (wanted && result.language !== 'unknown' && !result.translatedFrom && baseLang(result.language) !== baseLang(wanted)) result.translationUnavailable = wanted;
      return result;
    } catch (error) {
      const kind = fail(route, error);
      if (final(kind)) break;
      if (kind === 'rate_limited' || kind === 'bot_check') coolingUntil[backend] = Date.now() + COOLDOWN_MS;
    }
  }
  giveUp(videoId, failures);
}

function giveUp(videoId: string, failures: Failure[]): never {
  const real = failures.filter((f) => f.message !== 'yt-dlp not installed');
  const kinds = new Set(real.map((f) => f.kind));
  const pick: FailureKind =
    (['private', 'age_restricted', 'unavailable', 'rate_limited', 'bot_check', 'no_captions', 'network'] as FailureKind[]).find((k) => kinds.has(k)) ?? 'unknown';
  const detail = real.map((f) => `${f.route}: ${f.message}`).join(' | ');
  throw new YouTubeToolError(pick, `Could not get a transcript for ${videoId}. ${detail}`);
}
